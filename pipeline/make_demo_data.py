def main():
    path = DATA_DIR / "tmdb_demo.sqlite"
    if path.exists():
        path.unlink()
    con = open_db(path)
    name_to_id = {s[0]: 900001 + i for i, s in enumerate(SHOWS)}
    for i, (name, lang, y0, y1, status, genres, net, creators, kws, ov, pop, seasons, rt) in enumerate(SHOWS):
        row = {
            "id": name_to_id[name], "name": name, "original_name": name, "original_language": lang,
            "origin_country": [], "overview": ov, "tagline": "", "popularity": pop,
            "vote_average": 0, "vote_count": 0,
            "first_air_date": f"{y0}-01-01", "last_air_date": f"{y1}-01-01" if y1 else "",
            "status": status, "type": "Miniseries" if seasons == 1 and y0 == y1 else "Scripted",
            "adult": False, "poster_path": None, "backdrop_path": None,
            "number_of_seasons": seasons, "number_of_episodes": 0, "episode_run_time": [rt],
            "genres": genres, "networks": [net], "created_by": creators, "keywords": kws,
            "cast": [], "providers": [], "providers_link": None, "recommendations": [],
        }
        con.execute("INSERT OR REPLACE INTO shows VALUES (?,?,?)", (row["id"], json.dumps(row), time.time()))
    con.commit()
    print(f"Wrote {len(SHOWS)} demo shows to {path}")


if __name__ == "__main__":
    main()
